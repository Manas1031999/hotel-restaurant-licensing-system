-- ---------- Users ----------
CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('APPLICANT', 'REVIEWER', 'APPROVER', 'ADMIN')),
    active        BOOLEAN      NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL
);

-- ---------- Business ----------
CREATE TABLE businesses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name VARCHAR(200) NOT NULL,
    business_type VARCHAR(30)  NOT NULL CHECK (business_type IN ('HOTEL', 'RESTAURANT', 'LODGE', 'RESORT')),
    owner_name    VARCHAR(150) NOT NULL,
    mobile_number VARCHAR(15)  NOT NULL UNIQUE,
    email         VARCHAR(150) UNIQUE,
    district      VARCHAR(100) NOT NULL,
    address       VARCHAR(500) NOT NULL,
    is_active     BOOLEAN      NOT NULL,
    owner_id      BIGINT       REFERENCES app_users (id),
    created_at    TIMESTAMP(6) NOT NULL
);

-- ---------- License applications ----------
CREATE TABLE license_applications (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id        BIGINT       NOT NULL REFERENCES businesses (id),
    application_number VARCHAR(50)  UNIQUE,
    application_status VARCHAR(30)  NOT NULL
        CHECK (application_status IN ('PENDING', 'UNDER_REVIEW', 'INSPECTION', 'APPROVED', 'REJECTED')),
    remarks            VARCHAR(1000),
    submitted_at       TIMESTAMP(6) NOT NULL,
    reviewed_at        TIMESTAMP(6)
);

CREATE TABLE application_status_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id  BIGINT       NOT NULL REFERENCES license_applications (id),
    previous_status VARCHAR(30)
        CHECK (previous_status IN ('PENDING', 'UNDER_REVIEW', 'INSPECTION', 'APPROVED', 'REJECTED')),
    new_status      VARCHAR(30)  NOT NULL
        CHECK (new_status IN ('PENDING', 'UNDER_REVIEW', 'INSPECTION', 'APPROVED', 'REJECTED')),
    remarks         VARCHAR(1000),
    changed_by      VARCHAR(50),
    changed_at      TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_status_history_application ON application_status_history (application_id);

-- ---------- Licenses ----------
CREATE TABLE licenses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL UNIQUE REFERENCES license_applications (id),
    license_number VARCHAR(50)  NOT NULL UNIQUE,
    issued_date    DATE         NOT NULL,
    valid_until    DATE         NOT NULL,
    status         VARCHAR(255) NOT NULL CHECK (status IN ('ACTIVE', 'EXPIRED', 'INACTIVE')),
    created_at     TIMESTAMP(6) NOT NULL
);

CREATE TABLE license_renewals (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_id           BIGINT       NOT NULL REFERENCES licenses (id),
    previous_valid_until DATE         NOT NULL,
    new_valid_until      DATE         NOT NULL,
    renewal_date         DATE         NOT NULL,
    created_at           TIMESTAMP(6) NOT NULL
);

-- ---------- Payments ----------
CREATE TABLE payments (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_id            BIGINT        NOT NULL REFERENCES licenses (id),
    amount                NUMERIC(10, 2) NOT NULL,
    status                VARCHAR(255)  NOT NULL CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
    transaction_reference VARCHAR(255)  UNIQUE,
    payment_date          TIMESTAMP(6),
    created_at            TIMESTAMP(6)
);

-- ---------- Workflow rules ----------
CREATE TABLE workflow_transition (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_type VARCHAR(30) CHECK (business_type IN ('HOTEL', 'RESTAURANT', 'LODGE', 'RESORT')),
    from_status   VARCHAR(30) NOT NULL
        CHECK (from_status IN ('PENDING', 'UNDER_REVIEW', 'INSPECTION', 'APPROVED', 'REJECTED')),
    to_status     VARCHAR(30) NOT NULL
        CHECK (to_status IN ('PENDING', 'UNDER_REVIEW', 'INSPECTION', 'APPROVED', 'REJECTED')),
    required_role VARCHAR(20) NOT NULL CHECK (required_role IN ('APPLICANT', 'REVIEWER', 'APPROVER', 'ADMIN')),
    active        BOOLEAN      NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_workflow_lookup ON workflow_transition (business_type, from_status, active);

-- ---------- Audit ----------
CREATE TABLE audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action        VARCHAR(50)  NOT NULL,
    entity_type   VARCHAR(50)  NOT NULL,
    entity_id     VARCHAR(100),
    outcome       VARCHAR(10)  NOT NULL CHECK (outcome IN ('SUCCESS', 'FAILURE')),
    actor         VARCHAR(100) NOT NULL,
    ip_address    VARCHAR(64),
    request_uri   VARCHAR(255),
    detail        VARCHAR(1000),
    error_message VARCHAR(1000),
    duration_ms   BIGINT       NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_audit_entity ON audit_log (entity_type, entity_id);
CREATE INDEX idx_audit_created_at ON audit_log (created_at);

-- ---------- Notification outbox ----------
CREATE TABLE notification_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template        VARCHAR(50)   NOT NULL CHECK (template IN (
                        'APPLICATION_SUBMITTED', 'APPLICATION_STATUS_CHANGED',
                        'LICENSE_ISSUED', 'LICENSE_RENEWED', 'LICENSE_EXPIRED')),
    recipient       VARCHAR(150)  NOT NULL,
    subject         VARCHAR(255)  NOT NULL,
    body            VARCHAR(4000) NOT NULL,
    status          VARCHAR(10)   NOT NULL CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    attempts        INTEGER       NOT NULL,
    last_error      VARCHAR(1000),
    next_attempt_at TIMESTAMP(6)  NOT NULL,
    created_at      TIMESTAMP(6)  NOT NULL,
    sent_at         TIMESTAMP(6)
);

CREATE INDEX idx_outbox_due ON notification_outbox (status, next_attempt_at);
